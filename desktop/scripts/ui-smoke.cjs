const { app, BrowserWindow, session, nativeTheme } = require('electron')
const { join } = require('node:path')
const { writeFileSync } = require('node:fs')
const assert = require('node:assert/strict')
const root = process.argv[2]
app.setPath('userData', join(root,'user-data'))
app.commandLine.appendSwitch('lang','en-US')
app.whenReady().then(async () => {
  session.defaultSession.webRequest.onBeforeRequest({urls:['http://*/*','https://*/*']}, (_details, callback) => callback({cancel:true}))
  const win = new BrowserWindow({show:false,width:1000,height:780,webPreferences:{preload:join(__dirname,'ui-fixture.cjs'),sandbox:false,contextIsolation:true,backgroundThrottling:false,offscreen:true}})
  const errors=[]
  win.webContents.on('console-message',event=>{if(event.level==='error')errors.push(event.message)})
  const js = async code => {try{return await win.webContents.executeJavaScript(code)}catch(error){throw new Error(`Renderer script failed: ${code}`,{cause:error})}}
  const pause = () => new Promise(resolve=>setTimeout(resolve,80))
  const wait = async condition => {
    for(let i=0;i<80;i++){if(await js(condition))return;await pause()}
    throw new Error(`Timed out: ${condition}\n${await js('document.body.innerText')}`)
  }
  const click = async text => { await js(`Array.from(document.querySelectorAll('button')).find(x=>x.textContent.trim()===${JSON.stringify(text)})?.click()`);await pause() }
  const nav = async title => {await js(`document.querySelector('button[title=${JSON.stringify(title)}]')?.click()`);await pause()}
  const field = async (selector,value) => {await js(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}))})()`);await pause()}
  const choose = async (selector,value) => {await js(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});el.value=${JSON.stringify(value)};el.dispatchEvent(new Event('change',{bubbles:true}))})()`);await pause()}
  const ruleTypes = () => js("Array.from(document.querySelectorAll('#custom-rule-type option'),option=>option.value).sort()")
  const layout = async (group,server) => {
    await js(`document.querySelector('[role=group][aria-label="Group view"] button[title=${JSON.stringify(group)}]')?.click()`)
    await js(`document.querySelector('[role=group][aria-label="Proxy view"] button[title=${JSON.stringify(server)}]')?.click()`)
    await pause()
  }
  const select = async (label,value) => {await js(`(()=>{const el=document.querySelector('select[data-testid=${JSON.stringify(label.toLowerCase())}]');el.value=${JSON.stringify(value)};el.dispatchEvent(new Event('change',{bubbles:true}))})()`);await pause()}
  const capture = async name => {await new Promise(resolve=>setTimeout(resolve,400));writeFileSync(join(root,name+'.png'),(await win.webContents.capturePage()).toPNG())}
  try {
    await win.loadFile(join(__dirname,'../out/renderer/index.html'))
    await wait("document.body.innerText.includes('Could not load the app')")
    await js('window.qa.allowAuth()');await click('Try again')
    await wait("document.body.innerText.includes('Core running')")
    assert.equal(await js("document.body.innerText.includes('Install helper')"),false)
    assert.equal(await js("document.querySelector('[data-testid=config-update-hint]') !== null"),false)
    await js('window.qa.profileConfigUpdate(true)')
    await wait("document.querySelector('[data-testid=config-update-hint]')?.textContent.includes('Configuration updated. Reconnect to apply.')")
    assert.equal(await js("(()=>{const hint=document.querySelector('[data-testid=config-update-hint]');const section=hint.closest('section');const button=Array.from(section.querySelectorAll('button')).find(x=>x.textContent.trim()==='Disconnect');const details=section.querySelector('div.border-t');return button.getBoundingClientRect().bottom<=hint.getBoundingClientRect().top && hint.getBoundingClientRect().bottom<=details.getBoundingClientRect().top})()"),true)
    await capture('home-config-update-en')
    await js('window.qa.profileConfigUpdate(false)')
    await wait("document.querySelector('[data-testid=config-update-hint]') === null")
    await js('window.qa.profileConfigUpdate(true)')
    await wait("document.querySelector('[data-testid=config-update-hint]') !== null")
    await click('Disconnect');await wait("document.body.innerText.includes('Ready to connect')")
    assert.equal(await js("document.querySelector('[data-testid=config-update-hint]') !== null"),false)
    await click('Connect');await wait("document.body.innerText.includes('Core running')")
    assert.equal(await js("document.querySelector('[data-testid=config-update-hint]') !== null"),false)
    await js("Array.from(document.querySelectorAll('button')).find(x=>x.textContent.includes('Custom Rules:'))?.click()")
    await wait("document.querySelector('#custom-rule-type') !== null")
    const englishTypes = await ruleTypes()
    assert.equal(englishTypes.length,31)
    assert.deepEqual(await js("Array.from(document.querySelectorAll('#custom-rule-type optgroup'),x=>x.label)"),['Process','Domain','IP','Ports & inbound','Other'])
    await js("document.querySelector('[role=dialog] button[aria-label=Close]')?.click()")
    await wait("document.querySelector('[role=dialog]') === null")
    await nav('Proxies');await click('Main')
    // Group button includes its selected server; click it by aria-expanded instead.
    await js("document.querySelector('button[aria-expanded]')?.click()")
    await wait("document.querySelector('ul[aria-label=Servers]') !== null")
    assert.ok(await js("document.querySelectorAll('ul[aria-label=Servers] button').length")<=20)
    assert.equal(await js("Array.from(document.querySelectorAll('[role=group][aria-label$=view] button')).every(x=>!x.textContent.trim() && x.getAttribute('aria-label'))"),true)
    for(const group of ['List','Grid']) {
      await layout(group,'List')
      await js("document.querySelector('button[aria-label=\"Expand all groups\"]').click()")
      await wait("document.querySelectorAll('button[aria-expanded=true]').length === 12")
      await js("document.querySelector('button[aria-label=\"Collapse all groups\"]').click()")
      await wait("document.querySelectorAll('button[aria-expanded=true]').length === 0 && document.querySelectorAll('ul[aria-label=Servers]').length === 0")
    }
    await js("document.querySelector('button[aria-expanded]')?.click()")
    // All nine combinations must keep long lists virtualized and reach their last server.
    for (const group of ['List','Grid','Carousel']) {
      for (const server of ['List','Large grid','Small grid']) {
        await layout(group,server)
        assert.ok(await js("document.querySelector('ul[aria-label=Servers] button') !== null"))
        assert.ok(await js("document.querySelectorAll('ul[aria-label=Servers] button').length")<150)
        assert.equal(await js("document.querySelectorAll('[data-proxy-description]').length > 0"),server==='Large grid')
        if(server==='Large grid') {
          assert.ok(await js("document.querySelector('[data-proxy-transport]').textContent.includes(' : ')") )
          assert.ok(await js("document.querySelector('ul[aria-label=Servers] button').getBoundingClientRect().height")<=72)
        }
        await js("(()=>{const list=document.querySelector('ul[aria-label=Servers]');list.scrollTop=list.scrollHeight;list.dispatchEvent(new Event('scroll',{bubbles:true}))})()")
        await wait("Array.from(document.querySelectorAll('ul[aria-label=Servers] button')).some(x=>x.title==='Server 0999')")
        assert.ok(await js("(()=>{const list=document.querySelector('ul[aria-label=Servers]');const last=Array.from(list.querySelectorAll('button')).find(x=>x.title==='Server 0999');return list.getBoundingClientRect().bottom-last.getBoundingClientRect().bottom})()")>=11)
        if(server==='Large grid') await capture('proxies-'+group.toLowerCase()+'-large-grid')
        if(group==='Grid' && server==='Small grid') await capture('proxies-grid-small-grid')
      }
    }
    assert.equal(await js("document.querySelectorAll('[data-group-layout=carousel] [aria-expanded]').length"),0)
    assert.equal(await js("document.querySelectorAll('[role=tabpanel] ul').length"),1)
    assert.equal(await js("document.querySelector('button[aria-label=\"Expand all groups\"]')"),null)
    await js("document.querySelectorAll('[role=tab]')[9].click()")
    await wait("document.querySelector('[role=tablist]').scrollLeft > 100")
    assert.equal(await js("document.querySelectorAll('[role=tabpanel] ul button').length"),6)
    assert.equal(await js("document.querySelectorAll('[role=tab][aria-selected=true]').length"),1)
    await capture('carousel-selected-group')
    await js("document.querySelector('[role=tab][aria-selected=true]').dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true}))")
    await wait("document.querySelector('[role=tab][aria-selected=true]').title === 'Main'")
    await wait("document.querySelector('[role=tablist]').scrollLeft < 2")
    await js("document.querySelector('[role=tablist]').dispatchEvent(new WheelEvent('wheel',{deltaY:180,bubbles:true,cancelable:true}))")
    await wait("document.querySelector('[role=tablist]').scrollLeft >= 170")
    await js("document.querySelector('[role=tablist]').dispatchEvent(new WheelEvent('wheel',{deltaY:-180,bubbles:true,cancelable:true}))")
    await wait("document.querySelector('[role=tablist]').scrollLeft < 2")
    const dragPoint = await js("(()=>{const rect=document.querySelector('[role=tablist]').getBoundingClientRect();return {x:Math.round(rect.left+rect.width*0.7),y:Math.round(rect.top+rect.height/3)}})()")
    win.webContents.sendInputEvent({type:'mouseMove',...dragPoint});await pause()
    win.webContents.sendInputEvent({type:'mouseDown',...dragPoint,button:'left',clickCount:1});await pause()
    win.webContents.sendInputEvent({type:'mouseMove',x:dragPoint.x-180,y:dragPoint.y});await pause()
    win.webContents.sendInputEvent({type:'mouseUp',x:dragPoint.x-180,y:dragPoint.y,button:'left',clickCount:1});await pause()
    await wait("document.querySelector('[role=tablist]').scrollLeft >= 170")
    assert.equal(await js("document.querySelector('[role=tab][aria-selected=true]').title"),'Main')
    await js("document.querySelectorAll('[role=tab]')[1].click()")
    await wait("document.querySelector('[role=tab][aria-selected=true]').title === 'Media'")
    await js("document.querySelectorAll('[role=tab]')[0].click()")
    await layout('Carousel','Large grid')
    await capture('carousel-metadata')
    assert.equal(await js("(()=>{const bar=document.querySelector('[data-testid=proxies-toolbar]');const y=bar.querySelector('h2').getBoundingClientRect().top;return Array.from(bar.querySelectorAll('input,select,button')).every(x=>Math.abs(x.getBoundingClientRect().top-y)<5)})()"),true)
    await layout('Grid','Small grid')
    // Independent choices survive navigation and a renderer reload.
    await nav('Home');await nav('Proxies')
    assert.equal(await js("document.querySelector('[data-group-layout]').dataset.groupLayout"),'grid')
    assert.equal(await js("document.querySelector('ul[aria-label=Servers]').dataset.serverLayout"),'small-grid')
    await js("document.querySelectorAll('ul[aria-label=Servers] button')[1]?.click()")
    await pause()
    assert.equal(await js("document.querySelectorAll('ul[aria-label=Servers] button')[1]?.getAttribute('aria-pressed')"),'true')
    await layout('List','List')
    await field('input[aria-label="Search servers"]','0999')
    await wait("document.querySelectorAll('ul[aria-label=Servers] button').length === 1")
    await js("document.querySelector('button[aria-label=\"Collapse all groups\"]').click()")
    await wait("document.querySelectorAll('button[aria-expanded=true]').length === 0")
    assert.equal(await js("document.querySelector('input[aria-label=\"Search servers\"]').value"),'0999')
    await js("document.querySelector('button[aria-label=\"Expand all groups\"]').click()")
    await wait("document.querySelectorAll('ul[aria-label=Servers] button').length === 1")
    await nav('Home');await nav('Proxies')
    assert.equal(await js("document.querySelector('input[aria-label=\"Search servers\"]').value"),'0999')
    await nav('Profiles')
    assert.equal(await js("document.body.innerText.includes('SECRET_TOKEN')"),false)
    await field('input[placeholder="Subscription URL"]','https://example.invalid/broken')
    await click('Import URL')
    await wait("document.body.innerText.includes('Import failed for test')")
    assert.equal(await js("document.querySelector('input[placeholder=\"Subscription URL\"]').value"),'https://example.invalid/broken')
    await nav('Logs')
    await js("window.qa.emitLog('[401] [error] https://example.invalid/SECRET_TOKEN token=PRIVATE newest')")
    await wait("document.body.innerText.includes('newest')")
    assert.equal(await js("document.body.innerText.includes('PRIVATE') || document.body.innerText.includes('SECRET_TOKEN')"),false)
    assert.ok(await js("(()=>{const e=document.querySelector('div.overflow-auto');return e.scrollHeight-e.scrollTop-e.clientHeight<2})()"))
    await js("(()=>{const e=document.querySelector('div.overflow-auto');e.scrollTop=0;e.dispatchEvent(new Event('scroll',{bubbles:true}))})()")
    await pause();await js("window.qa.emitLog('[402] [info] AFTER_PAUSE')");await pause()
    assert.equal(await js("document.body.innerText.includes('AFTER_PAUSE')"),false)
    await js("document.querySelector('button[aria-label=Dismiss]')?.click()")
    await nav('Settings');await select('Language','ru');await select('Theme','light')
    await wait("document.documentElement.lang==='ru' && document.documentElement.classList.contains('light')")
    assert.ok(await js("document.body.innerText.toLowerCase().includes('внешний вид')"), await js('document.body.innerText'))
    await capture('settings-ru-light')
    // Regression: localization must change only labels, never filter out rule types.
    await nav('Главная')
    await js("Array.from(document.querySelectorAll('button')).find(x=>x.textContent.includes('Свои правила:'))?.click()")
    await wait("document.querySelector('#custom-rule-type') !== null")
    assert.deepEqual(await ruleTypes(),englishTypes)
    assert.deepEqual(await js("Array.from(document.querySelectorAll('#custom-rule-type optgroup'),x=>x.label)"),['Процесс','Домен','IP','Порты и входящие подключения','Другое'])
    await click('Справка');await wait("document.querySelector('#custom-rules-help') !== null")
    assert.equal(await js("document.querySelector('#custom-rules-help').innerText.includes('https://')"),true)
    await capture('rules-help-ru-light')
    await click('Справка')
    await choose('#custom-rule-type','DOMAIN-SUFFIX')
    await field('[role=dialog] input:not([type=checkbox])','example.com')
    await click('Добавить правило')
    await wait("document.querySelector('[role=dialog]').innerText.includes('example.com') && document.querySelector('[role=dialog]').innerText.includes('Включено 1 из 1')")
    await js("document.querySelector('[role=dialog] button[aria-label=Закрыть]')?.click()")
    await wait("document.querySelector('[role=dialog]') === null")
    await wait("Array.from(document.querySelectorAll('button')).some(x=>x.textContent.includes('Свои правила: 1'))")
    await capture('home-rule-count-ru-light')
    await js("Array.from(document.querySelectorAll('button')).find(x=>x.textContent.includes('Свои правила:'))?.click()")
    await wait("document.querySelector('[role=dialog] button[aria-label=\"Удалить правило DOMAIN-SUFFIX\"]') !== null")
    await js("document.querySelector('[role=dialog] button[aria-label=\"Удалить правило DOMAIN-SUFFIX\"]')?.click()")
    await wait("document.querySelector('[role=dialog]').innerText.includes('Choose a type') || !document.querySelector('[role=dialog]').innerText.includes('example.com')")
    await js("document.querySelector('[role=dialog] button[aria-label=Закрыть]')?.click()")
    await wait("document.querySelector('[role=dialog]') === null")
    await wait("Array.from(document.querySelectorAll('button')).some(x=>x.textContent.includes('Свои правила: 0'))")
    await nav('Настройки')
    await select('Theme','dark');await capture('settings-ru-dark')
    await nav('Главная');await wait("document.querySelector('h2')?.textContent === 'Test subscription'");await capture('home-ru-dark')
    await js('window.qa.profileConfigUpdate(true)')
    await wait("document.querySelector('[data-testid=config-update-hint]')?.textContent.includes('Конфигурация обновлена. Переподключитесь, чтобы применить.')")
    await capture('home-config-update-ru-dark')
    await js('window.qa.profileConfigUpdate(false)')
    await nav('Настройки');await select('Theme','system');nativeTheme.themeSource='light'
    await wait("document.documentElement.classList.contains('light')")
    nativeTheme.themeSource='dark'
    await wait("document.documentElement.classList.contains('dark')")
    await win.webContents.reload();await wait("document.documentElement.lang==='ru'")
    await wait("document.body.innerText.includes('Не удалось загрузить приложение')")
    await js('window.qa.allowAuth()');await click('Повторить')
    await wait("document.body.innerText.includes('Настройки')")
    await nav('Серверы')
    assert.equal(await js("document.querySelector('[data-group-layout]').dataset.groupLayout"),'list')
    await js("document.querySelector('[role=group][aria-label=\"Вид групп\"] button[title=Сетка]')?.click()")
    await js("document.querySelector('[role=group][aria-label=\"Вид прокси\"] button[title=\"Крупная сетка\"]')?.click()")
    await js("document.querySelector('button[aria-expanded]')?.click()")
    await wait("document.querySelector('ul[data-server-layout=large-grid]') !== null")
    await win.webContents.reload();await wait("document.body.innerText.includes('Не удалось загрузить приложение')")
    await js('window.qa.allowAuth()');await click('Повторить')
    await wait("document.body.innerText.includes('Test subscription')")
    await nav('Серверы');await wait("document.querySelector('[data-group-layout=grid]') !== null")
    await js("document.querySelector('button[aria-expanded]')?.click()")
    await wait("document.querySelector('ul[data-server-layout=large-grid]') !== null")
    win.setSize(760,650);await pause();await capture('proxies-ru-narrow')
    assert.equal(await js("document.documentElement.scrollWidth <= window.innerWidth"),true)
    assert.equal(errors.length,0,errors.join('\n'))
    console.log('UI smoke passed: 9 server layouts, icon controls, expand/collapse all, carousel wheel/drag/tab selection, bottom spacing, YAML metadata, persistence, rule localization and counter, startup, logs and themes')
    console.log('Screenshots: '+root)
    app.exit(0)
  } catch(error) {console.error(error);await capture('failure');console.log('Screenshots: '+root);app.exit(1)}
})
