const { app, BrowserWindow, session } = require('electron')
const { join } = require('node:path')
const { mkdirSync, writeFileSync } = require('node:fs')
const assert = require('node:assert/strict')
app.setPath('userData',join(process.argv[2],'user-data'))
app.commandLine.appendSwitch('force-device-scale-factor','1')
app.whenReady().then(async()=>{
  session.defaultSession.webRequest.onBeforeRequest({urls:['http://*/*','https://*/*']},(_,cb)=>cb({cancel:true}))
  const output=join(__dirname,'../design-preview/screenshots');mkdirSync(output,{recursive:true})
  const win=new BrowserWindow({show:false,width:800,height:700,frame:false,webPreferences:{preload:join(__dirname,'ui-fixture.cjs'),additionalArguments:['--connections-preview'],sandbox:false,contextIsolation:true,offscreen:true,backgroundThrottling:false}})
  const js=async code=>{try{return await win.webContents.executeJavaScript(code)}catch(error){throw new Error(code,{cause:error})}}
  const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms))
  const click=selector=>js(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const wait=async code=>{for(let i=0;i<80;i++){if(await js(code))return;await pause(100)}throw Error('Timed out: '+code)}
  const capture=async name=>{await pause(200);writeFileSync(join(output,name+'.png'),(await win.webContents.capturePage()).toPNG())}
  try{
    await win.loadFile(join(__dirname,'../out/renderer/index.html'))
    await wait('document.querySelector("[data-testid=quick-proxy-trigger]") !== null')
    await wait('document.querySelector("[data-testid=sidebar-version]").textContent !== "—"')
    assert.equal(await js('document.querySelector("[data-testid=profile-title]").textContent'),'Test subscription')
    assert.equal(await js('document.querySelector("[data-testid=core-status]").dataset.state'),'running')
    await wait('document.querySelector("[data-testid=public-ip]").textContent.includes("203.0.113.42")')
    assert.equal(await js('document.querySelector("[data-testid=vpn-widget] h2").textContent'),'Подключение')
    assert.equal(await js('document.querySelector("[data-testid=connection-widget]").innerText.includes("Подключение")'),false)
    assert.equal(await js('document.querySelector("[data-testid=public-ip] [role=img]").getAttribute("aria-label")'),'DE')
    await capture('11-client-home-800')
    assert.equal(await js('getComputedStyle(document.body).backgroundColor'),'rgb(0, 0, 0)')
    assert.equal(await js('document.querySelector("main").scrollHeight <= document.querySelector("main").clientHeight'),true,'Normal home fits 800x700')
    await click('[data-testid=quick-proxy-trigger]');await wait('document.querySelector("[data-testid=quick-proxy-popover]") !== null')
    const inBounds='(()=>{const r=document.querySelector("[data-testid=quick-proxy-popover]").getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight})()'
    await pause(200);assert.ok(await js(inBounds));await capture('12-client-quick-proxy')
    await js(`(()=>{const input=document.querySelector('[data-testid=quick-proxy-popover] input');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'0999');input.dispatchEvent(new Event('input',{bubbles:true}))})()`)
    await wait('document.querySelectorAll("[data-proxy-option]").length===1')
    await click('[data-proxy-option]');await wait('document.querySelector("[data-testid=quick-proxy-trigger]").textContent.includes("0999")')
    await js('window.qa.publicIp({state:"pending",retryAt:Date.now()+60000})')
    await wait('document.querySelector("[data-testid=public-ip]").dataset.state === "pending"')
    assert.equal(await js('document.querySelector("[data-testid=public-ip] [role=img]")'),null)
    assert.equal(await js('document.querySelector("[data-testid=public-ip]").textContent.includes("203.0.113")'),false)
    await capture('18-client-ip-cooldown')
    await js('window.qa.publicIp({state:"ready",ip:"2001:db8:1234:5678:abcd:abcd:abcd:abcd",countryCode:"NL",provider:"test fixture"})')
    await wait('document.querySelector("[data-testid=public-ip]").textContent.includes("2001:db8")')
    assert.ok(await js('document.documentElement.scrollWidth <= innerWidth'))
    await capture('19-client-ipv6')
    await js('window.qa.publicIp({state:"ready",ip:"203.0.113.42",countryCode:"DE",provider:"test fixture"})')
    await click('[data-testid=quick-proxy-trigger]');await pause(100)
    win.webContents.sendInputEvent({type:'keyDown',keyCode:'Escape'});win.webContents.sendInputEvent({type:'keyUp',keyCode:'Escape'})
    await wait('document.querySelector("[data-testid=quick-proxy-popover]") === null')
    await wait('document.activeElement.dataset.testid === "quick-proxy-trigger"')
    win.setSize(800,560);await pause(150);await capture('13-client-home-minimum')
    await click('[data-testid=quick-proxy-trigger]');await pause(200);assert.ok(await js(inBounds))
    await js('document.querySelector("main").scrollTop=50');await pause(200);assert.ok(await js(inBounds))
    win.webContents.sendInputEvent({type:'keyDown',keyCode:'Escape'});win.webContents.sendInputEvent({type:'keyUp',keyCode:'Escape'})
    await click('[role=group][aria-label="Режим подключения"] button:last-child')
    await wait('document.querySelector("[role=alertdialog]") !== null')
    await js(`Array.from(document.querySelectorAll('[role=alertdialog] button')).find(b=>b.textContent==='Отмена').click()`)
    await wait('document.querySelector("[role=alertdialog]") === null')
    assert.ok(await js('document.querySelector("[role=group][aria-label=\\"Режим подключения\\"] button:first-child").getAttribute("aria-pressed")==="true"'))
    await click('button[title="Настройки"]')
    await js(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='Логи').click()`)
    await wait('document.body.innerText.includes("test log")')
    win.setSize(800,700)
    await click('button[title="Главная"]')
    await js(`window.qa.profileMetadata({title:'Cheezy · Personal',supportUrl:'https://example.invalid/support',announce:'Профиль обновлён. Новые серверы доступны в списке прокси.'})`)
    await wait('document.querySelector("[data-testid=profile-title]").textContent === "Cheezy · Personal"')
    await wait('document.querySelector("[data-testid=announcement]") !== null')
    await click('[data-testid=subscription-support]')
    assert.deepEqual(await js('window.qa.externalUrls()'),['https://example.invalid/support'])
    assert.equal(await js('document.querySelector("[data-testid=sidebar-version]").textContent'),require('../package.json').version)
    await capture('14-client-announcement-support')
    await click('[data-testid=sidebar-toggle]')
    assert.equal(await js('document.querySelector("[data-testid=sidebar]").getBoundingClientRect().width'),64)
    await capture('15-client-sidebar-collapsed')
    await win.webContents.reload()
    await wait('document.querySelector("[data-testid=sidebar]")?.dataset.collapsed === "true"')
    await click('[data-testid=sidebar-toggle]')
    await js(`window.qa.profileMetadata({title:'',announce:'Объявление '.repeat(120)})`)
    await wait('document.querySelector("[data-testid=announcement] p")?.scrollHeight > 112')
    assert.equal(await js('document.querySelector("[data-testid=profile-title]").textContent'),'Test subscription')
    assert.ok(await js('document.documentElement.scrollWidth <= innerWidth'))
    await click('[data-testid=announcement] button')
    assert.equal(await js('document.querySelector("[data-testid=announcement]")'),null)
    await js(`window.qa.profileMetadata({announce:'Новое сообщение'})`)
    await wait('document.querySelector("[data-testid=announcement]") !== null')
    await click('[data-testid=announcement] button')
    await js(`window.qa.coreError('Example core error')`)
    await wait('document.querySelector("[data-testid=core-status]").dataset.state === "error"')
    assert.ok(await js('document.querySelector("[data-testid=core-status]").className.includes("bg-destructive")'))
    await capture('16-client-core-error')
    await js('window.qa.coreError(undefined)')
    await wait('document.querySelector("[data-testid=core-status]").dataset.state === "running"')
    assert.ok(await js('document.querySelector("[data-testid=core-status]").className.includes("text-emerald" )'))
    await click('[data-testid=quit-app]')
    await wait('window.qa.quitCalls() === 1')
    console.log('Production widgets passed: 800x700 fit, 800x560, portal bounds, search/select, Escape focus return, mode cancellation, settings navigation, sidebar persistence, title fallback, Support, Announce, status colors and quit action. Renders: '+output)
    app.exit(0)
  }catch(e){console.error(e);await capture('client-widget-failure');app.exit(1)}
})
